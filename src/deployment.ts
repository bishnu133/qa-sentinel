import fs from "node:fs";
import path from "node:path";
import type { Config, ServiceConfig } from "./config.js";
import { checkDeployment } from "./feature/manifest.js";
import { git } from "./git.js";
import type { VerificationReport } from "./verification.js";

/**
 * Is the change the tests were written for running in the environment they ran against? Tests written for a change
 * that isn't deployed yet fail for that reason alone; reporting that as FAILED would be a false alarm. Services with a
 * `version` endpoint are asked which commit they run; when a needed change isn't there and only test runs failed, the
 * result is WAITING_FOR_DEPLOYMENT instead.
 */
export interface DeploymentNeed {
  service: ServiceConfig;
  sha: string;
  repo?: string;
}

export interface DeploymentState {
  service: string;
  sha: string;
  deployed?: string;
  includesChange?: boolean;
  error?: string;
}

export async function deploymentStates(needs: DeploymentNeed[], environment: string, baseUrl: string): Promise<DeploymentState[]> {
  const out: DeploymentState[] = [];
  for (const n of needs) {
    if (!n.service.version) continue; // can't tell: not counted either way
    const d = await checkDeployment({ service: n.service.name, source: "git", sha: n.sha, merged: true }, n.service, environment, baseUrl, n.repo && fs.existsSync(n.repo) ? n.repo : undefined);
    out.push({ service: n.service.name, sha: n.sha, deployed: d?.sha, includesChange: d?.includesChange, error: d?.error });
  }
  return out;
}

export const notDeployed = (states: DeploymentState[]) => states.filter((s) => s.includesChange === false);

/** FAILED only because of test runs, while a change the tests need isn't deployed: WAITING_FOR_DEPLOYMENT. */
export function applyDeploymentGate(r: VerificationReport, states: DeploymentState[]): VerificationReport {
  const waiting = notDeployed(states);
  const failedOther = r.checks.some((c) => c.status === "failed" && c.name !== "tests");
  const detail = waiting.map((w) => `${w.service} runs ${w.deployed?.slice(0, 8) ?? "?"}, the tests need ${w.sha.slice(0, 8)}`).join("; ");
  const checks = states.length
    ? [...r.checks, { name: "deployment" as const, status: waiting.length ? ("blocked" as const) : ("passed" as const), detail: waiting.length ? `not deployed yet: ${detail}` : `deployed: ${states.map((s) => `${s.service}@${s.deployed?.slice(0, 8) ?? "?"}`).join(", ")}` }]
    : r.checks;
  if (r.status === "FAILED" && waiting.length && !failedOther) return { ...r, checks, status: "WAITING_FOR_DEPLOYMENT" };
  return { ...r, checks };
}

/** The service commits an agent branch was generated from ("Generated by qa-sentinel x from orders@abc, web@def."). */
export function needsFromCommits(c: Config, cwd: string, base: string, head = "HEAD"): DeploymentNeed[] {
  let log = "";
  try {
    log = git(cwd, ["log", "--format=%B%x1e", `${base}..${head}`]);
  } catch {
    return [];
  }
  const out = new Map<string, DeploymentNeed>();
  for (const m of log.matchAll(/Generated by qa-sentinel \S+ from ([^\n]+?)\.?\n/g)) {
    for (const part of m[1].split(/,\s*/)) {
      const [name, sha] = part.trim().split("@");
      const service = c.workspace.services.find((s) => s.name === name);
      if (service && sha && /^[0-9a-f]{7,40}$/.test(sha) && !out.has(name)) out.set(name, { service, sha, repo: path.resolve(cwd, service.path) });
    }
  }
  return [...out.values()];
}
