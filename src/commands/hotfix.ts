import path from "node:path";
import { loadConfig } from "../config.js";
import { git, isGitRepo } from "../git.js";
import { findCherryPicks, safeRef, type CherryPick } from "../release/git.js";
import { findService } from "../run.js";
import { postToStory } from "../reporting/statusComment.js";
import { jiraContext, markdownToJiraWiki } from "../scm/jira.js";
import { log } from "../log.js";
import { EXIT_STILL_WAITING } from "./postDeploy.js";

export interface HotfixOptions {
  cwd: string;
  service: string;
  servicePath?: string;
  /** The hotfix commit(s) on the hotfix / release branch. */
  commit?: string[];
  /** Or a range, e.g. production..hotfix/orders-1. */
  range?: string;
  story?: string;
  post?: boolean;
  json?: boolean;
  /** Exit 75 (the same "still waiting" code as post-deploy) while a hotfix commit is not on the main branch yet. */
  failIfWaiting?: boolean;
  /** Also exit 1 when a commit is on the main branch but no tests were written from it `graceDays` after it landed. Includes failIfWaiting. */
  strict?: boolean;
  graceDays?: number;
  /** For tests: the clock. */
  now?: Date;
}

export type HotfixState = "waiting-for-cherry-pick" | "cherry-picked" | "on-target";

export interface HotfixRow {
  commit: string;
  subject: string;
  state: HotfixState;
  picks: CherryPick[];
  /** Test commits (in the test repo) generated from the hotfix or from its cherry-pick. */
  testCommits: string[];
}

const keyOf = (pattern: string, text: string) => new RegExp(`(?<![A-Za-z0-9])(${pattern})(?![0-9])`).exec(text)?.[1]?.toUpperCase();

/**
 * `qa-sentinel hotfix` (no AI): where a hotfix stands. A hotfix is branched from production and cherry-picked to the
 * main branch. Tests are written once, when the change is on main; until then the gap report's regression selection
 * is what runs against the hotfix environment. This matches each hotfix commit to its cherry-pick (a
 * `cherry-pick -x` line, or the same change by patch id) and says whether tests were written from it yet.
 */
export async function hotfixCommand(o: HotfixOptions): Promise<number> {
  const cwd = path.resolve(o.cwd);
  if (o.graceDays !== undefined) {
    if (!o.strict) throw new Error("--grace-days only works with --strict");
    if (!Number.isFinite(o.graceDays) || o.graceDays < 0) throw new Error(`--grace-days must be a number of days, 0 or more (got ${o.graceDays})`);
  }
  const c = loadConfig(cwd);
  const service = findService(c, o.service, cwd, o.servicePath);
  const repo = path.resolve(cwd, service.path);
  if (!isGitRepo(repo)) throw new Error(`${repo} is not a git repository`);
  if (o.range && o.commit?.length) throw new Error("Pass --commit or --range, not both");
  for (const x of [...(o.commit ?? []), ...(o.range ? [o.range] : [])]) safeRef(x);
  const shas = o.range ? git(repo, ["rev-list", "--no-merges", "--reverse", o.range, "--"]).split("\n").filter(Boolean) : (o.commit ?? []).map((x) => git(repo, ["rev-parse", "--verify", "--end-of-options", `${x}^{commit}`]));
  if (!shas.length) throw new Error("Pass --commit <sha> (repeatable) or --range <base>..<hotfix-branch>");
  const target = ["origin/" + c.ci.targetBranch, c.ci.targetBranch].find((b) => {
    try {
      git(repo, ["rev-parse", "--verify", "-q", b]);
      return true;
    } catch {
      return false;
    }
  });
  if (!target) throw new Error(`The target branch ${c.ci.targetBranch} is not in ${repo}: fetch it first`);

  let testLog = "";
  try {
    if (isGitRepo(cwd)) testLog = git(cwd, ["log", "-n", "1000", "--format=%H%x09%B%x1e", "--grep=Generated by qa-sentinel", "HEAD"]);
  } catch {
    /* no test history */
  }
  // generate records "<service>@<head sha>" of the commit it ran for; with merge commits that is a later commit than the
  // cherry-pick itself, so a recorded head that contains the commit counts.
  const esc = service.name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const recorded = testLog
    .split("\x1e")
    .map((x) => x.trim())
    .filter(Boolean)
    .map((m) => ({ testCommit: m.split("\t")[0], head: new RegExp(`${esc}@([0-9a-f]{40})`).exec(m)?.[1] }))
    .filter((x): x is { testCommit: string; head: string } => !!x.head);
  const contains = (head: string, sha: string) => {
    try {
      git(repo, ["merge-base", "--is-ancestor", sha, head]);
      return true;
    } catch {
      return false;
    }
  };
  const testCommitsFor = (find: string[]) => recorded.filter((r) => find.some((s) => r.head === s || contains(r.head, s))).map((r) => r.testCommit);

  const rows: HotfixRow[] = shas.map((commit) => {
    const picks = findCherryPicks(repo, commit, target);
    const onTarget = (() => {
      try {
        git(repo, ["merge-base", "--is-ancestor", commit, target]);
        return true;
      } catch {
        return false;
      }
    })();
    return { commit, subject: git(repo, ["log", "-1", "--format=%s", commit]), state: onTarget ? "on-target" : picks.length ? "cherry-picked" : "waiting-for-cherry-pick", picks, testCommits: testCommitsFor([commit, ...picks.map((p) => p.commit)]) };
  });

  const story = o.story?.toUpperCase() ?? rows.map((r) => keyOf(c.requirements.storyKeyPattern, r.subject)).find(Boolean);
  const STATE: Record<HotfixState, string> = { "waiting-for-cherry-pick": `⏳ not on ${c.ci.targetBranch} yet`, "cherry-picked": `✅ on ${c.ci.targetBranch}`, "on-target": `✅ already on ${c.ci.targetBranch}` };
  const md = [
    `### Hotfix · ${service.name}${story ? ` · ${story}` : ""}`,
    "",
    "| Hotfix commit | Change | On " + c.ci.targetBranch + " | Tests written |",
    "| --- | --- | --- | --- |",
    ...rows.map((r) => `| \`${r.commit.slice(0, 8)}\` | ${r.subject.replace(/\|/g, "/")} | ${STATE[r.state]}${r.picks.length ? ` as ${r.picks.map((p) => `\`${p.commit.slice(0, 8)}\` (${p.how})`).join(", ")}` : ""} | ${r.testCommits.length ? `✅ ${r.testCommits.map((t) => `\`${t.slice(0, 8)}\``).join(", ")}` : r.state === "waiting-for-cherry-pick" ? "– (after the cherry-pick)" : "⏳ not yet: tests are written once the change is on the main branch (`qa-sentinel generate`)"} |`),
    "",
    "Until the change is on the main branch, the regression selection in the hotfix MR's gap report is what runs against the hotfix environment.",
  ].join("\n");

  if (!o.json) log.info(md);
  if (o.post) {
    const jira = jiraContext(c.requirements.jira);
    if (!jira || !story) log.warn("--post: needs Jira configured and a story key (--story, or one in the commit message)");
    else {
      const r = await postToStory(c, jira, story, { name: `hotfix:${service.name}`, wiki: markdownToJiraWiki(md), legacyKind: `hotfix-${service.name}`, legacyMarker: `qa-sentinel:hotfix-${service.name}`, cwd });
      log.ok(`Jira ${story}: hotfix status ${r.action}`);
    }
  }
  const waiting = rows.filter((r) => r.state === "waiting-for-cherry-pick");
  // When did a commit reach the main branch? A cherry-pick: its own date. A commit that is on the branch: the first merge commit
  // that brought it (a hotfix branch merged today keeps its old commit date); with no merge (fast-forward), its own date is all there is.
  const landedAt = (r: HotfixRow): number => {
    const ct = (x: string) => Number(git(repo, ["log", "-1", "--format=%ct", x])) * 1000;
    const times = r.picks.map((p) => ct(p.commit));
    if (r.state === "on-target") {
      let first = "";
      try {
        first = git(repo, ["log", "--ancestry-path", "--merges", "--reverse", "--format=%ct", `${r.commit}..${target}`]).split("\n").find(Boolean) ?? "";
      } catch {
        /* no path: use the commit's own date */
      }
      times.push(first ? Number(first) * 1000 : ct(r.commit));
    }
    return Math.max(...times);
  };
  const grace = (o.graceDays ?? 2) * 86_400_000;
  const now = (o.now ?? new Date()).getTime();
  const late = o.strict ? rows.filter((r) => r.state !== "waiting-for-cherry-pick" && !r.testCommits.length && now - landedAt(r) > grace) : [];
  if (o.failIfWaiting || o.strict) {
    // 75 (still waiting) wins over 1 (late): while anything waits, run again later.
    if (waiting.length) log.warn(`${waiting.length} hotfix commit(s) are not on ${c.ci.targetBranch} yet: exit ${EXIT_STILL_WAITING}`);
    else if (late.length) log.warn(`${late.length} hotfix commit(s) are on ${c.ci.targetBranch} but have no tests after ${o.graceDays ?? 2} day(s): exit 1`);
  }
  if (o.json) process.stdout.write(JSON.stringify({ service: service.name, story, target, rows, waiting: waiting.map((r) => r.commit), late: late.map((r) => r.commit) }, null, 2) + "\n");
  if ((o.failIfWaiting || o.strict) && waiting.length) return EXIT_STILL_WAITING;
  if (late.length) return 1;
  return 0;
}
