import path from "node:path";
import { loadConfig } from "../config.js";
import { git, isGitRepo } from "../git.js";
import { findCherryPicks, type CherryPick } from "../release/git.js";
import { findService } from "../run.js";
import { postToStory } from "../reporting/statusComment.js";
import { jiraContext, markdownToJiraWiki } from "../scm/jira.js";
import { log } from "../log.js";

export interface HotfixOptions {
  cwd: string;
  service: string;
  servicePath?: string;
  /** The hotfix commit(s) on the hotfix / release branch. */
  commit?: string[];
  /** Or a range, e.g. production..hotfix/orders-1. */
  range?: string;
  story?: string;
  post?: boolean;
  json?: boolean;
}

export type HotfixState = "waiting-for-cherry-pick" | "cherry-picked" | "on-target";

export interface HotfixRow {
  commit: string;
  subject: string;
  state: HotfixState;
  picks: CherryPick[];
  /** Test commits (in the test repo) generated from the hotfix or from its cherry-pick. */
  testCommits: string[];
}

const keyOf = (pattern: string, text: string) => new RegExp(`(?<![A-Za-z0-9])(${pattern})(?![0-9])`).exec(text)?.[1]?.toUpperCase();

/**
 * `qa-sentinel hotfix` (no AI): where a hotfix stands. A hotfix is branched from production and cherry-picked to the
 * main branch. Tests are written once, when the change is on main; until then the gap report's regression selection
 * is what runs against the hotfix environment. This matches each hotfix commit to its cherry-pick (a
 * `cherry-pick -x` line, or the same change by patch id) and says whether tests were written from it yet.
 */
export async function hotfixCommand(o: HotfixOptions): Promise<number> {
  const cwd = path.resolve(o.cwd);
  const c = loadConfig(cwd);
  const service = findService(c, o.service, cwd, o.servicePath);
  const repo = path.resolve(cwd, service.path);
  if (!isGitRepo(repo)) throw new Error(`${repo} is not a git repository`);
  const shas = o.range ? git(repo, ["rev-list", "--no-merges", "--reverse", o.range]).split("\n").filter(Boolean) : (o.commit ?? []).map((x) => git(repo, ["rev-parse", "--verify", `${x}^{commit}`]));
  if (!shas.length) throw new Error("Pass --commit <sha> (repeatable) or --range <base>..<hotfix-branch>");
  const target = ["origin/" + c.ci.targetBranch, c.ci.targetBranch].find((b) => {
    try {
      git(repo, ["rev-parse", "--verify", "-q", b]);
      return true;
    } catch {
      return false;
    }
  });
  if (!target) throw new Error(`The target branch ${c.ci.targetBranch} is not in ${repo}: fetch it first`);

  let testLog = "";
  try {
    if (isGitRepo(cwd)) testLog = git(cwd, ["log", "-n", "1000", "--format=%H%x09%B%x1e", "--grep=Generated by qa-sentinel", "HEAD"]);
  } catch {
    /* no test history */
  }
  const testCommitsFor = (shasToFind: string[]) =>
    testLog
      .split("\x1e")
      .map((x) => x.trim())
      .filter(Boolean)
      .filter((m) => shasToFind.some((s) => m.includes(`${service.name}@${s}`)))
      .map((m) => m.split("\t")[0]);

  const rows: HotfixRow[] = shas.map((commit) => {
    const picks = findCherryPicks(repo, commit, target);
    const onTarget = (() => {
      try {
        git(repo, ["merge-base", "--is-ancestor", commit, target]);
        return true;
      } catch {
        return false;
      }
    })();
    return { commit, subject: git(repo, ["log", "-1", "--format=%s", commit]), state: onTarget ? "on-target" : picks.length ? "cherry-picked" : "waiting-for-cherry-pick", picks, testCommits: testCommitsFor([commit, ...picks.map((p) => p.commit)]) };
  });

  const story = o.story?.toUpperCase() ?? rows.map((r) => keyOf(c.requirements.storyKeyPattern, r.subject)).find(Boolean);
  const STATE: Record<HotfixState, string> = { "waiting-for-cherry-pick": `⏳ not on ${c.ci.targetBranch} yet`, "cherry-picked": `✅ on ${c.ci.targetBranch}`, "on-target": `✅ already on ${c.ci.targetBranch}` };
  const md = [
    `### Hotfix · ${service.name}${story ? ` · ${story}` : ""}`,
    "",
    "| Hotfix commit | Change | On " + c.ci.targetBranch + " | Tests written |",
    "| --- | --- | --- | --- |",
    ...rows.map((r) => `| \`${r.commit.slice(0, 8)}\` | ${r.subject.replace(/\|/g, "/")} | ${STATE[r.state]}${r.picks.length ? ` as ${r.picks.map((p) => `\`${p.commit.slice(0, 8)}\` (${p.how})`).join(", ")}` : ""} | ${r.testCommits.length ? `✅ ${r.testCommits.map((t) => `\`${t.slice(0, 8)}\``).join(", ")}` : r.state === "waiting-for-cherry-pick" ? "– (after the cherry-pick)" : "⏳ not yet: tests are written once the change is on the main branch (`qa-sentinel generate`)"} |`),
    "",
    "Until the change is on the main branch, the regression selection in the hotfix MR's gap report is what runs against the hotfix environment.",
  ].join("\n");

  if (o.json) process.stdout.write(JSON.stringify({ service: service.name, story, target, rows }, null, 2) + "\n");
  else log.info(md);
  if (o.post) {
    const jira = jiraContext(c.requirements.jira.baseUrl);
    if (!jira || !story) log.warn("--post: needs Jira configured and a story key (--story, or one in the commit message)");
    else {
      const r = await postToStory(c, jira, story, { name: `hotfix:${service.name}`, wiki: markdownToJiraWiki(md), legacyKind: `hotfix-${service.name}` });
      log.ok(`Jira ${story}: hotfix status ${r.action}`);
    }
  }
  return 0;
}
