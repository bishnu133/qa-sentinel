import { ARTIFACT_GLOBS } from "../run.js";
import { requirementItems, resolveRequirements } from "../requirements.js";
import { indexSource } from "../analysis/testIndex.js";
import { log } from "../log.js";
import { type CurrentAc, acHash } from "./format.js";
import { checkExpectationLockDetailed, overrideFindings, storyOfExpectedPath, type LockFinding } from "./lock.js";

/** qa-sentinel's own commits say so in their message (generate writes "Generated by qa-sentinel <version> …"). */
export const AGENT_COMMIT = /^Generated by qa-sentinel\b/m;
/** The story's AC hashes when qa-sentinel wrote a commit: `QA-Sentinel-ACs: SHOP-101 AC-1=3f2a9c1e5b7d AC-2=…`. */
const AC_TRAILER = /^QA-Sentinel-ACs: ([A-Za-z][A-Za-z0-9]*-\d+)((?: [^\s=]+=[0-9a-f]{12})+)\s*$/gm;

/** The trailer generate adds to its commit, so later checks know which AC texts its changes were made for. */
export function acTrailer(story: string | undefined, acs: { id: string; text: string }[]): string | undefined {
  if (!story || !acs.length) return undefined;
  return `QA-Sentinel-ACs: ${story.toUpperCase()} ${acs.map((a) => `${a.id}=${acHash(a.text)}`).join(" ")}`;
}

export interface BranchCommit {
  sha: string;
  author: string;
  agent: boolean;
  body: string;
  changes: FileChange[];
}

/** Non-merge commits on the branch since `base`, oldest first, with what each changed (computed once). */
export function branchCommits(repo: string, base: string): BranchCommit[] {
  const raw = git(repo, ["log", "--reverse", "--no-merges", "--format=%H%x09%an <%ae>%x00%B%x1e", `${base}..HEAD`, "--", "."]);
  return raw
    .split("\x1e")
    .map((r) => r.trim())
    .filter(Boolean)
    .map((r) => {
      const [head, body = ""] = r.split("\0");
      const [sha, author] = head.split("\t");
      return { sha, author, body, agent: AGENT_COMMIT.test(body), changes: changesBetween(repo, `${sha}^`, sha).filter((x) => !matchesAny(x.path, ARTIFACT_GLOBS)) };
    });
}

/** Story keys a set of changes touches: expected files and @story tags (test or describe) in changed tests. */
function storiesTouched(repo: string, expectedDir: string, ref: string, changes: FileChange[]): string[] {
  const keys = new Set<string>();
  for (const ch of changes) {
    const s = storyOfExpectedPath(expectedDir, ch.path);
    if (s) keys.add(s);
    const src = /\.(spec|test)\.[cm]?[jt]sx?$/.test(ch.path) ? showFile(repo, ref, ch.path) : undefined;
    if (src) for (const t of indexSource(ch.path, src)) for (const k of [...t.stories, ...[...(t.describe ?? "").matchAll(/@story:([A-Za-z][A-Za-z0-9]*-\d+)/g)].map((m) => m[1])]) keys.add(k.toUpperCase());
  }
  return [...keys];
}

/** The stories' current ACs from Jira (several at a time), so a changed AC can unlock its expectations. */
export async function currentAcsFor(c: Config, stories: string[]): Promise<Map<string, CurrentAc[]>> {
  const out = new Map<string, CurrentAc[]>();
  if (!stories.length || c.requirements.source !== "jira") return out;
  const queue = [...stories];
  const failed: string[] = [];
  await Promise.all(
    Array.from({ length: Math.min(4, queue.length) }, async () => {
      for (let key = queue.shift(); key; key = queue.shift()) {
        try {
          const req = await resolveRequirements(c, { keyHints: [key] });
          if (req.storyKey?.toUpperCase() === key && requirementItems(req).length) out.set(key, requirementItems(req).map((a) => ({ id: a.id, text: a.text })));
          else failed.push(key);
        } catch (e) {
          failed.push(`${key} (${(e as Error).message})`);
        }
      }
    }),
  );
  if (failed.length) log.warn(`expectation lock: couldn't read the current ACs of ${failed.join(", ")} from Jira; their expectations stay locked unless qa-sentinel's commit recorded them`);
  return out;
}

/** Lines in `after` that aren't in `before` (as a multiset). */
function addedBetween(before: string | undefined, after: string | undefined): string[] {
  if (after === undefined) return [];
  const old = new Map<string, number>();
  for (const l of (before ?? "").split("\n")) old.set(l, (old.get(l) ?? 0) + 1);
  return after.split("\n").filter((l) => {
    const n = old.get(l) ?? 0;
    if (n > 0) old.set(l, n - 1);
    return n === 0;
  });
}

/** AC hashes qa-sentinel recorded in its commits (latest wins), for stories Jira can't be asked about. */
function trailerAcs(commits: BranchCommit[]): Map<string, CurrentAc[]> {
  const out = new Map<string, CurrentAc[]>();
  for (const cm of commits.filter((x) => x.agent)) {
    for (const m of cm.body.matchAll(AC_TRAILER)) out.set(m[1].toUpperCase(), m[2].trim().split(" ").map((p) => ({ id: p.split("=")[0], hash: p.split("=")[1] })));
  }
  return out;
}

/**
 * The lock on a branch with several authors (`verify --policy` on an agent MR). The branch's NET change since the
 * base is checked, so something reverted later doesn't count. A finding is qa-sentinel's when one of its commits
 * made a change of that kind to the same test or AC; otherwise a person made it, which is accepted and listed as an
 * override. A person who rewrites qa-sentinel's commit takes it over: it shows as their override, never hidden.
 */
export async function lockByAuthor(repo: string, c: Config, base: string): Promise<Finding[]> {
  const commits = branchCommits(repo, base);
  if (!commits.length) return [];
  const net = changesBetween(repo, base, "HEAD").filter((x) => !matchesAny(x.path, ARTIFACT_GLOBS));
  const fromJira = await currentAcsFor(c, storiesTouched(repo, c.tests.expectedDir, base, net));
  const currentAcs = new Map([...trailerAcs(commits), ...fromJira]);
  // What is locked is always decided from the branch base: a person's commit in between can't open it for the AI.
  // An expected file new on this branch is locked from the qa-sentinel commit that wrote it (generate writes it before
  // the tests): a later AI commit may not move its values.
  const created = new Map<string, string>();
  for (const cm of commits.filter((x) => x.agent)) for (const ch of cm.changes) if (ch.status === "A" && storyOfExpectedPath(c.tests.expectedDir, ch.path) && !created.has(ch.path)) created.set(ch.path, cm.sha);
  const lockedBy = (f: string) => showFile(repo, base, f) ?? (created.has(f) ? showFile(repo, created.get(f)!, f) : undefined);
  const lock = (changes: FileChange[], from: string, to: string) => checkExpectationLockDetailed({ expectedDir: c.tests.expectedDir, changes, before: (f) => showFile(repo, from, f), after: (f) => showFile(repo, to, f), lockedBy, currentAcs });
  const found = [
    ...lock(net, base, "HEAD"),
    ...[...created].filter(([f]) => net.some((x) => x.path === f)).flatMap(([f, sha]) => lock([{ path: f, status: showFile(repo, "HEAD", f) === undefined ? "D" : "M" }], sha, "HEAD")),
  ];
  // test.fail added by qa-sentinel's own commits (only a person marks a known defect).
  const defects = commits
    .filter((x) => x.agent)
    .flatMap((cm) => checkKnownDefectMarkers(cm.changes, repo, `${cm.sha}^`, (f) => addedBetween(showFile(repo, `${cm.sha}^`, f), showFile(repo, cm.sha, f))).map((x) => ({ ...x, message: `qa-sentinel's commit ${cm.sha.slice(0, 8)}: ${x.message}` })));
  if (!found.length) return defects;
  const agentFound = new Map<string, string>();
  for (const cm of commits.filter((x) => x.agent)) for (const f of lock(cm.changes, `${cm.sha}^`, cm.sha)) agentFound.set(`${f.rule}|${f.file}|${f.subject}`, cm.sha);
  const people = [...new Set(commits.filter((x) => !x.agent).map((x) => x.author))].join(", ") || "a person";
  const out: Finding[] = [];
  for (const f of found) {
    const sha = agentFound.get(`${f.rule}|${f.file}|${f.subject}`);
    if (f.level !== "violation" || f.always) out.push({ level: f.level, rule: f.rule, file: f.file, message: f.message });
    else if (sha) out.push({ level: "violation", rule: f.rule, file: f.file, message: `qa-sentinel's commit ${sha.slice(0, 8)}: ${f.message}` });
    else out.push(...overrideFindings([f as LockFinding], people));
  }
  return [...out, ...defects];
}
