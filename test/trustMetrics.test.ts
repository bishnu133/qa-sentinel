const manifest = (o: Partial<Manifest> & { runId: string; kind: string }): Manifest =>
  ({ qaSentinelVersion: "x", startedAt: "2026-10-01T00:00:00Z", configSha256: "", testRepo: { sha: "" }, service: { name: "s", path: "p", base: "a", head: "b", changedFiles: [] }, dependencies: [], requirements: { source: "none", acCount: 0 }, ...o }) as Manifest;
const agentCommit = (o: Partial<AgentCommit> = {}): AgentCommit => ({ sha: "a", date: "2026-10-01T00:00:00Z", files: ["tests/a.spec.ts"], state: "merged-unedited", ...o });

describe("flakiness of agent-written tests (B4)", () => {
  it("reads the titles of the tests a commit added, from its added lines only", () => {
    const repo = tmp("qas-added-");
    g(repo, "init", "-q", "-b", "main");
    commit(repo, "tests/a.spec.ts", `test("old one @story:S-1", async () => {});\n`, "init");
    commit(repo, "tests/a.spec.ts", `test("old one @story:S-1", async () => {});\ntest("rejects a past slot @ac:AC-2", async () => {});\nit.skip('single quotes ok', () => {});\n// test("commented? still counted", x)\nconst t = "not a test";\n`, "add");
    const titles = addedTestTitles(repo, g(repo, "rev-parse", "HEAD"), ["tests/a.spec.ts"]);
    expect(titles).toContain("rejects a past slot @ac:AC-2");
    expect(titles).toContain("single quotes ok");
    expect(titles).not.toContain("old one @story:S-1");
    expect(addedTestTitles(repo, g(repo, "rev-parse", "HEAD"), [])).toEqual([]);
  });

  it("describe blocks, steps, helpers and regex tests are not tests", () => {
    const repo = tmp("qas-added2-");
    g(repo, "init", "-q", "-b", "main");
    commit(repo, "tests/a.spec.ts", "// base\n", "init");
    const body = [
      'test.describe("Orders", () => {',
      '  test.only("a real test", async () => {',
      '    await test.step("post the order", async () => {});',
      '    expect(/x/.test("abc")).toBe(true);',
      "  });",
      '  test.fixme("a pending one", async () => {});',
      '  test.slow("a slow one", async () => {});',
      "});",
      'describe("Jest block", () => { it("jest style", () => {}); });',
      'submit("not a test");',
      "",
    ].join("\n");
    commit(repo, "tests/a.spec.ts", body, "add");
    expect(addedTestTitles(repo, g(repo, "rev-parse", "HEAD"), ["tests/a.spec.ts"]).sort()).toEqual(["a pending one", "a real test", "a slow one", "jest style"]);
  });

  it("a flaky name matches a test by its whole name or its last part after ›, never by a piece of the title", () => {
    expect(sameTest("works", "works")).toBe(true);
    expect(sameTest("Orders › post › it works with a coupon", "works")).toBe(false);
    expect(sameTest("file.spec.ts › Orders › works", "works")).toBe(true);
    expect(sameTest("Orders", "Orders")).toBe(true);
    const m = computeMetrics([], [agentCommit({ addedTests: ["works", "a real test", "Orders"] })], undefined, [], { flakyNames: ["Orders › it works with a coupon", "x › a real test"] });
    expect(m.agentTestFlakiness).toMatchObject({ agentTests: 3, flaky: 1, flakyTests: ["a real test"] });
  });

  it("agentCommits lists the tests each agent commit added", () => {
    const repo = tmp("qas-agent-added-");
    g(repo, "init", "-q", "-b", "main");
    commit(repo, "README.md", "x\n", "init");
    commit(repo, "tests/slot.spec.ts", `test("fourth order is rejected @ac:AC-3", () => {});\n`, "test(svc): QA agent updates\n\nGenerated by qa-sentinel 0.8.0 from svc@abc.\nRun: run-1");
    const commits = agentCommits(repo, "main");
    expect(commits).toHaveLength(1);
    expect(commits[0].addedTests).toEqual(["fourth order is rejected @ac:AC-3"]);
  });

  it("collects flaky names from every verification.json under the folders, and the rate counts agent tests that appear in them", () => {
    const dir = tmp("qas-flaky-");
    fs.mkdirSync(path.join(dir, "runs/r1"), { recursive: true });
    fs.mkdirSync(path.join(dir, "runs/r2"), { recursive: true });
    fs.writeFileSync(path.join(dir, "runs/r1/verification.json"), JSON.stringify({ status: "VERIFIED", flaky: ["orders › fourth order is rejected @ac:AC-3", "someone else's test"] }));
    fs.writeFileSync(path.join(dir, "runs/r2/verification.json"), JSON.stringify({ status: "VERIFIED" }));
    fs.writeFileSync(path.join(dir, "runs/r2/not-ours.json"), "{");
    const names = collectFlaky([dir]);
    expect(names.sort()).toEqual(["orders › fourth order is rejected @ac:AC-3", "someone else's test"]);

    const m = computeMetrics([], [agentCommit({ addedTests: ["fourth order is rejected @ac:AC-3", "past slot rejected", "returns the slot"] }), agentCommit({ sha: "b", addedTests: ["past slot rejected"] })], undefined, [], { flakyNames: names });
    // Three distinct agent-written tests; one is on a flaky list (JUnit names carry a describe prefix, so "contains" counts).
    expect(m.agentTestFlakiness).toEqual({ agentTests: 3, flaky: 1, rate: 33.3, flakyTests: ["fourth order is rejected @ac:AC-3"] });
    expect(metricsMarkdown(m)).toContain("| Agent-written tests that were flaky | 33.3% (1/3) |");
    expect(computeMetrics([], [], undefined, []).agentTestFlakiness).toMatchObject({ agentTests: 0, rate: null });
    expect(metricsMarkdown(computeMetrics([], [], undefined, []))).toContain("– (no agent tests found)");
  });
});

describe("hours from the service change to the test merge request (B4)", () => {
  const gen = (id: string, commitAt: string | undefined, openedAt: string | undefined) => manifest({ runId: id, kind: "generate", ...(commitAt || openedAt ? { trigger: { serviceCommitAt: commitAt, mrOpenedAt: openedAt } } : {}) });
  it("median and p90 over the generate runs that recorded both times; runs without them, and negative gaps, are left out", () => {
    const runs = [
      gen("a", "2026-10-01T08:00:00Z", "2026-10-01T09:00:00Z"), // 1 h
      gen("b", "2026-10-01T08:00:00Z", "2026-10-01T11:00:00Z"), // 3 h
      gen("c", "2026-10-01T08:00:00Z", "2026-10-02T08:00:00Z"), // 24 h
      gen("d", "2026-10-01T08:00:00Z", undefined),
      gen("e", undefined, undefined),
      gen("f", "2026-10-02T08:00:00Z", "2026-10-01T08:00:00Z"), // clock trouble: ignored
      manifest({ runId: "g", kind: "gap-report", trigger: { serviceCommitAt: "2026-10-01T08:00:00Z", mrOpenedAt: "2026-10-01T09:00:00Z" } }),
    ];
    const m = computeMetrics(runs, []);
    expect(m.mergeToMr).toEqual({ runs: 3, medianHours: 3, p90Hours: 24 });
    expect(metricsMarkdown(m)).toContain("median 3, p90 24 (3 run(s))");
    expect(computeMetrics([gen("e", undefined, undefined)], []).mergeToMr).toEqual({ runs: 0, medianHours: null, p90Hours: null });
  });

  it("the manifest helpers: commit date, patching a manifest, and noting when a deferred merge request was opened", () => {
    const repo = tmp("qas-date-");
    g(repo, "init", "-q", "-b", "main");
    const sha = commit(repo, "a.txt", "x\n", "c");
    expect(Date.parse(commitDate(repo, sha)!)).toBeGreaterThan(0);
    expect(commitDate(repo, "deadbeef")).toBeUndefined();
    const run = tmp("qas-run-");
    fs.writeFileSync(path.join(run, "manifest.json"), JSON.stringify({ runId: "r", kind: "generate", trigger: { serviceCommitAt: "2026-10-01T08:00:00.000Z" } }));
    markMrOpened(run);
    const m = JSON.parse(fs.readFileSync(path.join(run, "manifest.json"), "utf8"));
    expect(m.trigger.serviceCommitAt).toBe("2026-10-01T08:00:00.000Z");
    expect(Date.parse(m.trigger.mrOpenedAt)).toBeGreaterThan(0);
    expect(patchManifest(run, { mr: { project: "5", iid: "7", noteId: 11 } })).toBe(true);
    expect(JSON.parse(fs.readFileSync(path.join(run, "manifest.json"), "utf8")).mr).toEqual({ project: "5", iid: "7", noteId: 11 });
    expect(patchManifest(path.join(run, "nope"), {})).toBe(false);
  });
});

/** A mock GitLab with one merge request (project 5, !7): notes and emoji reactions. */
async function gitlab(awards: { name: string }[] | "gone" = [{ name: "thumbsup" }, { name: "thumbsup" }, { name: "thumbsdown" }, { name: "tada" }]) {
  const notes: { id: number; body: string; author: { id: number } }[] = [];
  const srv = await serve((req, url, body) => {
    const p = url.pathname.replace("/api/v4", "");
    const page = { headers: { "x-next-page": "" } };
    if (p === "/user") return { body: { id: 1 } };
    if (p === "/projects/5/merge_requests/7/notes") {
      if (req.method === "GET") return { body: notes, ...page };
      notes.push({ id: 11, body: JSON.parse(body).body, author: { id: 1 } });
      return { body: notes.at(-1) };
    }
    if (p === "/projects/5/merge_requests/7/notes/11" && req.method === "PUT") {
      notes[0].body = JSON.parse(body).body;
      return { body: {} };
    }
    if (p === "/projects/5/merge_requests/7/notes/11/award_emoji") return awards === "gone" ? { status: 404, body: {} } : { body: awards, ...page };
    return { status: 404, body: {} };
  });
  return { ...srv, notes };
}

describe("gap report usefulness votes (B4)", () => {
  async function repoWorld(gl: string, votes?: boolean) {
    const root = tmp("qas-votes-");
    const repo = path.join(root, "orders");
    fs.mkdirSync(repo);
    g(repo, "init", "-q", "-b", "main");
    const base = commit(repo, "src/a.ts", "export const a = 0;\n", "base");
    const head = commit(repo, "src/a.ts", "export const a = 0;\nexport const b = 1;\n", "change");
    g(root, "init", "-q", "-b", "main");
    writeConfig(
      root,
      ConfigSchema.parse({
        version: 1,
        mode: "existing",
        project: { name: "t" },
        workspace: { services: [{ name: "orders", path: "orders" }] },
        tests: { api: { framework: "playwright", runCommand: "npx playwright test" } },
        ci: { platform: "gitlab", gitlabUrl: gl },
        ...(votes === undefined ? {} : { reporting: { votes } }),
      }),
    );
    for (const [k, v] of Object.entries({ CI_PROJECT_ID: "5", CI_MERGE_REQUEST_IID: "7", CI_API_V4_URL: `${gl}/api/v4`, QA_SENTINEL_GITLAB_TOKEN: "t", CI_MERGE_REQUEST_DIFF_BASE_SHA: base, CI_MERGE_REQUEST_SOURCE_BRANCH_NAME: "feature/x", CI_MERGE_REQUEST_SOURCE_BRANCH_SHA: head, CI: "" })) vi.stubEnv(k, v);
    return { root, repo, head };
  }
  const runManifest = (root: string): Manifest => {
    const runs = path.join(root, ".qa-sentinel/runs");
    return JSON.parse(fs.readFileSync(path.join(runs, fs.readdirSync(runs)[0], "manifest.json"), "utf8"));
  };

  it("the gap report comment ends with the vote line and the run remembers which comment it is", async () => {
    const gl = await gitlab();
    try {
      const w = await repoWorld(gl.url);
      await gapReportCommand({ cwd: w.root, service: "orders", servicePath: w.repo, post: true });
      expect(gl.notes).toHaveLength(1);
      expect(gl.notes[0].body).toContain(VOTE_LINE);
      expect(gl.notes[0].body).toContain("👍 / 👎");
      expect(runManifest(w.root).mr).toEqual({ project: "5", iid: "7", noteId: 11 });
      // The report file itself has no vote line: reactions exist only on the merge request note.
      expect(fs.readFileSync(path.join(w.root, "qa-gap-report.md"), "utf8")).not.toContain("Was this useful");
    } finally {
      await gl.close();
    }
  });

  it("reporting.votes: false leaves the line out", async () => {
    const gl = await gitlab();
    try {
      const w = await repoWorld(gl.url, false);
      await gapReportCommand({ cwd: w.root, service: "orders", servicePath: w.repo, post: true });
      expect(gl.notes[0].body).not.toContain("Was this useful");
      expect(runManifest(w.root).mr?.noteId).toBe(11);
    } finally {
      await gl.close();
    }
  });

  it("metrics --online counts 👍 and 👎 on the comments; a comment is counted once; a deleted one is reported, not fatal; offline shows a dash", async () => {
    const gl = await gitlab();
    try {
      const w = await repoWorld(gl.url);
      await gapReportCommand({ cwd: w.root, service: "orders", servicePath: w.repo, post: true });
      const ctx = gitlabContext(gl.url, { QA_SENTINEL_GITLAB_TOKEN: "t", CI_API_V4_URL: `${gl.url}/api/v4` })!;
      const m1 = runManifest(w.root);
      const again = { ...m1, runId: "later-run" }; // a later run on the same merge request edits the same note
      expect(await fetchUsefulness(ctx, [m1, again, manifest({ runId: "x", kind: "generate" })])).toEqual({ notes: 1, up: 2, down: 1, unreadable: 0 });
      expect(await fetchUsefulness(ctx, [{ ...m1, mr: { project: "5", iid: "7", noteId: 99 } }])).toEqual({ notes: 0, up: 0, down: 0, unreadable: 1 });

      const out = path.join(w.root, "m.md");
      await metricsCommand({ cwd: w.root, out, fetch: false, online: true, env: { QA_SENTINEL_GITLAB_TOKEN: "t", CI_API_V4_URL: `${gl.url}/api/v4` } });
      expect(fs.readFileSync(out, "utf8")).toContain("| Gap report comments: 👍 / 👎 | 2 / 1 on 1 comment(s) |");
      await metricsCommand({ cwd: w.root, out, fetch: false });
      expect(fs.readFileSync(out, "utf8")).toContain("| Gap report comments: 👍 / 👎 | – (run `metrics --online` with a GitLab token) |");
      // --online without a token: a warning and the dash, not a crash.
      await metricsCommand({ cwd: w.root, out, fetch: false, online: true, env: {} });
      expect(fs.readFileSync(out, "utf8")).toContain("run `metrics --online`");
    } finally {
      await gl.close();
    }
  });
});
