import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { describe, expect, it } from "vitest";
import { agentCommits, collectManifests, computeMetrics, metricsMarkdown, parseSince, targetRef } from "../src/commands/metrics.js";

const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), "qas-metrics-"));
const sh = (cwd: string, ...args: string[]) => execFileSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" } }).trim();
const write = (repo: string, f: string, body: string) => {
  fs.mkdirSync(path.dirname(path.join(repo, f)), { recursive: true });
  fs.writeFileSync(path.join(repo, f), body);
};
const agent = (repo: string, branch: string, file: string, runId: string) => {
  sh(repo, "checkout", "-q", "-b", branch, "main");
  write(repo, file, `// by agent ${runId}\n`);
  sh(repo, "add", "-A");
  sh(repo, "commit", "-q", "-m", `test(svc): QA agent updates\n\nGenerated by qa-sentinel 0.6.0 from svc@abc.\nRisk: low. Verification: VERIFIED. Run: ${runId}`);
};

describe("metrics", () => {
  it("classifies agent commits: merged with/without edits (merge, fast-forward, squash), open, not merged", () => {
    const repo = tmp();
    sh(repo, "init", "-q", "-b", "main");
    write(repo, "README.md", "x\n");
    sh(repo, "add", "-A");
    sh(repo, "commit", "-q", "-m", "init");

    agent(repo, "qa-sentinel/a", "tests/a.spec.ts", "run-a"); // merged as is (merge commit)
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--no-ff", "-m", "Merge a", "qa-sentinel/a");

    agent(repo, "qa-sentinel/b", "tests/b.spec.ts", "run-b"); // a reviewer changed the test first
    write(repo, "tests/b.spec.ts", "// fixed by reviewer\n");
    sh(repo, "commit", "-qam", "review fix");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--no-ff", "-m", "Merge b", "qa-sentinel/b");

    agent(repo, "qa-sentinel/c", "tests/c.spec.ts", "run-c"); // squash merged
    const msg = sh(repo, "log", "-1", "--format=%B");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--squash", "qa-sentinel/c");
    sh(repo, "commit", "-q", "-m", `Squashed\n\n${msg}`);
    sh(repo, "branch", "-q", "-D", "qa-sentinel/c");

    agent(repo, "qa-sentinel/d", "tests/d.spec.ts", "run-d"); // fast-forward
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--ff-only", "qa-sentinel/d");

    agent(repo, "qa-sentinel/e", "tests/e.spec.ts", "run-e"); // still open
    sh(repo, "checkout", "-q", "main");

    const target = targetRef(repo, "main")!;
    expect(target).toBe("main");
    const commits = agentCommits(repo, target);
    const state = Object.fromEntries(commits.map((c) => [c.runId, c.state]));
    expect(state).toEqual({ "run-a": "merged-unedited", "run-b": "merged-edited", "run-c": "merged-unedited", "run-d": "merged-unedited", "run-e": "open" });
  });

  it("aggregates manifests (also from downloaded CI artifacts) and writes the report", () => {
    const dir = tmp();
    const man = (id: string, extra: object) => {
      fs.mkdirSync(path.join(dir, "job-1", ".qa-sentinel/runs", id), { recursive: true });
      fs.writeFileSync(path.join(dir, "job-1", ".qa-sentinel/runs", id, "manifest.json"), JSON.stringify({ runId: id, kind: "generate", startedAt: "2026-10-01T00:00:00Z", ...extra }));
    };
    man("g1", { outcome: "committed-verified", verification: { status: "VERIFIED" }, plan: { status: "valid", risk: "high", corrections: 0 }, agent: { status: "success", costUsd: 0.5, durationMs: 60000 } });
    man("g2", { outcome: "committed-failed", verification: { status: "FAILED" }, plan: { status: "valid", risk: "low", corrections: 2 }, agent: { status: "success", costUsd: 0.3, durationMs: 30000 } });
    man("g3", { outcome: "no-changes-needed", plan: { status: "valid", risk: "low", corrections: 0 }, agent: { status: "success", costUsd: 0.1 } });
    man("r1", { kind: "gap-report", outcome: "reported", plan: { status: "valid", corrections: 0 }, guardrails: { violations: 1, warnings: 0 }, agent: { status: "success", costUsd: 0.2, deniedToolCalls: 2 } });
    man("old", { startedAt: "2025-01-01T00:00:00Z" });
    fs.writeFileSync(path.join(dir, "job-1", "manifest.json"), "{not json");

    const ms = collectManifests([dir], new Date("2026-01-01"));
    expect(ms.map((m) => m.runId).sort()).toEqual(["g1", "g2", "g3", "r1"]);
    const m = computeMetrics(ms, [
      { sha: "1", date: "", files: [], state: "merged-unedited" },
      { sha: "2", date: "", files: [], state: "merged-unedited" },
      { sha: "3", date: "", files: [], state: "merged-edited" },
      { sha: "4", date: "", files: [], state: "open" },
    ]);
    expect(m.costUsd).toBe(1.1);
    expect(m.generate).toEqual({ reachedVerification: 2, verified: 1, verificationRate: 50 });
    expect(m.plans.repairRate).toBe(25);
    expect(m.guardrails).toEqual({ runsWithViolations: 1, deniedToolCalls: 2 });
    expect(m.mergeRequests.mergedWithoutEditsRate).toBe(66.7);
    expect(m.byKind.generate.runs).toBe(3);
    const md = metricsMarkdown(m);
    expect(md).toContain("| Test changes merged without human edits | 66.7% (2/3) |");
    expect(md).toContain("| generate | 3 | $0.300 |");
  });

  it("parses --since", () => {
    expect(Date.now() - parseSince("30d")!.getTime()).toBeGreaterThan(29 * 86_400_000);
    expect(parseSince("2026-01-02")!.toISOString()).toBe("2026-01-02T00:00:00.000Z");
    expect(() => parseSince("soon")).toThrow(/--since/);
  });
});
