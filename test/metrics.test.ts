import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { describe, expect, it } from "vitest";
import { agentCommits, collectManifests, computeMetrics, metricsMarkdown, parseSince, targetRef } from "../src/commands/metrics.js";

const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), "qas-metrics-"));
const sh = (cwd: string, ...args: string[]) => execFileSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" } }).trim();
const write = (repo: string, f: string, body: string) => {
  fs.mkdirSync(path.dirname(path.join(repo, f)), { recursive: true });
  fs.writeFileSync(path.join(repo, f), body);
};
const agent = (repo: string, branch: string, file: string, runId: string) => {
  sh(repo, "checkout", "-q", "-b", branch, "main");
  write(repo, file, `// by agent ${runId}\n`);
  sh(repo, "add", "-A");
  sh(repo, "commit", "-q", "-m", `test(svc): QA agent updates\n\nGenerated by qa-sentinel 0.6.0 from svc@abc.\nRisk: low. Verification: VERIFIED. Run: ${runId}`);
};

describe("metrics", () => {
  it("classifies agent commits: merged with/without edits (merge, fast-forward, squash), open, not merged", () => {
    const repo = tmp();
    sh(repo, "init", "-q", "-b", "main");
    write(repo, "README.md", "x\n");
    sh(repo, "add", "-A");
    sh(repo, "commit", "-q", "-m", "init");

    agent(repo, "qa-sentinel/a", "tests/a.spec.ts", "run-a"); // merged as is (merge commit)
    write(repo, "test-map.yaml", "a\n");
    sh(repo, "add", "-A");
    sh(repo, "commit", "-q", "--amend", "--no-edit");
    sh(repo, "checkout", "-q", "main");
    write(repo, "test-map.yaml", "other MR\n"); // another MR changes a shared file before the merge
    sh(repo, "add", "-A");
    sh(repo, "commit", "-q", "-m", "other work");
    sh(repo, "merge", "-q", "--no-ff", "-X", "theirs", "-m", "Merge a", "qa-sentinel/a");

    agent(repo, "qa-sentinel/b", "tests/b.spec.ts", "run-b"); // a reviewer changed the test first
    write(repo, "tests/b.spec.ts", "// fixed by reviewer\n");
    sh(repo, "commit", "-qam", "review fix");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--no-ff", "-m", "Merge b", "qa-sentinel/b");

    const squash = (branch: string, file: string, runId: string, edit: boolean, keepBranch: boolean) => {
      agent(repo, branch, file, runId);
      const msg = sh(repo, "log", "-1", "--format=%B");
      if (edit) {
        write(repo, file, "// reviewer\n");
        sh(repo, "commit", "-qam", "review");
      }
      sh(repo, "checkout", "-q", "main");
      sh(repo, "merge", "-q", "--squash", branch);
      sh(repo, "commit", "-q", "-m", `Squashed\n\n${msg}`);
      if (!keepBranch) sh(repo, "branch", "-q", "-D", branch);
    };
    squash("qa-sentinel/c", "tests/c.spec.ts", "run-c", false, true); // squash, as is, branch kept
    squash("qa-sentinel/f", "tests/f.spec.ts", "run-f", true, true); // squash with a reviewer edit
    squash("qa-sentinel/g", "tests/g.spec.ts", "run-g", false, false); // squash, branch deleted

    agent(repo, "qa-sentinel/d", "tests/d.spec.ts", "run-d"); // fast-forward
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--ff-only", "qa-sentinel/d");

    agent(repo, "qa-sentinel/e", "tests/e.spec.ts", "run-e"); // still open
    sh(repo, "checkout", "-q", "main");

    const target = targetRef(repo, "main")!;
    expect(target).toBe("main");
    const commits = agentCommits(repo, target);
    const state = Object.fromEntries(commits.map((c) => [c.runId, c.state]));
    expect(state).toEqual({
      "run-a": "merged-unedited",
      "run-b": "merged-edited",
      "run-c": "merged-unedited",
      "run-f": "merged-edited",
      "run-g": "merged-unknown",
      "run-d": "merged-unedited",
      "run-e": "open",
    });
    expect(commits).toHaveLength(7);
  });

  it("aggregates manifests (also from downloaded CI artifacts) and writes the report", () => {
    const dir = tmp();
    const man = (id: string, extra: object) => {
      fs.mkdirSync(path.join(dir, "job-1", ".qa-sentinel/runs", id), { recursive: true });
      fs.writeFileSync(path.join(dir, "job-1", ".qa-sentinel/runs", id, "manifest.json"), JSON.stringify({ runId: id, kind: "generate", startedAt: "2026-10-01T00:00:00Z", ...extra }));
    };
    man("g1", { outcome: "committed-verified", verification: { status: "VERIFIED" }, plan: { status: "valid", risk: "high", corrections: 0 }, agent: { status: "success", costUsd: 0.5, durationMs: 60000 } });
    man("g2", { outcome: "committed-failed", verification: { status: "FAILED" }, plan: { status: "valid", risk: "low", corrections: 2 }, agent: { status: "success", costUsd: 0.3, durationMs: 30000 } });
    man("g3", { outcome: "no-changes-needed", plan: { status: "valid", risk: "low", corrections: 0 }, agent: { status: "success", costUsd: 0.1 } });
    man("r1", { kind: "gap-report", outcome: "reported", plan: { status: "valid", corrections: 0 }, guardrails: { violations: 1, warnings: 0 }, agent: { status: "success", costUsd: 0.2, deniedToolCalls: 2 } });
    man("old", { startedAt: "2025-01-01T00:00:00Z" });
    fs.writeFileSync(path.join(dir, "job-1", "manifest.json"), "{not json");

    const ms = collectManifests([dir], new Date("2026-01-01"));
    expect(ms.map((m) => m.runId).sort()).toEqual(["g1", "g2", "g3", "r1"]);
    const m = computeMetrics(ms, [
      { sha: "1", date: "", files: [], state: "merged-unedited" },
      { sha: "2", date: "", files: [], state: "merged-unedited" },
      { sha: "3", date: "", files: [], state: "merged-edited" },
      { sha: "4", date: "", files: [], state: "open" },
      { sha: "5", date: "", files: [], state: "merged-unknown" },
    ]);
    expect(m.costUsd).toBe(1.1);
    expect(m.generate).toEqual({ reachedVerification: 2, verified: 1, verificationRate: 50 });
    expect(m.plans.repairRate).toBe(25);
    expect(m.guardrails).toEqual({ runsWithViolations: 1, deniedToolCalls: 2 });
    expect(m.mergeRequests.mergedWithoutEditsRate).toBe(66.7);
    expect(m.byKind.generate.runs).toBe(3);
    const md = metricsMarkdown(m);
    expect(md).toContain("| Test changes merged without human edits | 66.7% (2/3) |");
    expect(md).toContain("| generate | 3 | $0.300 |");
  });

  it("parses --since", () => {
    expect(Date.now() - parseSince("30d")!.getTime()).toBeGreaterThan(29 * 86_400_000);
    expect(parseSince("2026-01-02")!.toISOString()).toBe("2026-01-02T00:00:00.000Z");
    expect(() => parseSince("soon")).toThrow(/--since/);
  });
});

describe("metrics trend", () => {
  it("shows merged-without-edits by month", () => {
    const c = (date: string, state: any) => ({ sha: date + state, date, files: [], state });
    const m = computeMetrics([], [c("2026-08-03T00:00:00Z", "merged-edited"), c("2026-08-20T00:00:00Z", "merged-unedited"), c("2026-09-02T00:00:00Z", "merged-unedited"), c("2026-09-09T00:00:00Z", "open")]);
    expect(m.byMonth).toEqual([
      { month: "2026-08", merged: 2, unedited: 1, rate: 50 },
      { month: "2026-09", merged: 1, unedited: 1, rate: 100 },
    ]);
    expect(metricsMarkdown(m)).toContain("| 2026-09 | 1 | 100% (1) |");
  });
});

describe("metrics with merge request heads (GitLab refs/merge-requests/*/head)", () => {
  it("judges fast-forward merges and squash merges with deleted branches from the MR heads", async () => {
    const { fetchReviewRefs } = await import("../src/commands/metrics.js");
    const origin = tmp();
    sh(origin, "init", "-q", "--bare", "-b", "main");
    const repo = tmp();
    sh(repo, "init", "-q", "-b", "main");
    sh(repo, "remote", "add", "origin", origin);
    write(repo, "README.md", "x\n");
    sh(repo, "add", "-A");
    sh(repo, "commit", "-q", "-m", "init");

    // MR 1: fast-forward merge, a reviewer fixed the agent's test in the MR.
    agent(repo, "qa-sentinel/ff", "tests/ff.spec.ts", "run-ff");
    write(repo, "tests/ff.spec.ts", "// reviewer fix\n");
    sh(repo, "commit", "-qam", "review fix");
    sh(repo, "push", "-q", "origin", "qa-sentinel/ff:refs/merge-requests/1/head");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--ff-only", "qa-sentinel/ff");
    sh(repo, "branch", "-q", "-D", "qa-sentinel/ff");

    // MR 2: fast-forward merge as the agent wrote it.
    agent(repo, "qa-sentinel/ff2", "tests/ff2.spec.ts", "run-ff2");
    sh(repo, "push", "-q", "origin", "qa-sentinel/ff2:refs/merge-requests/2/head");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--ff-only", "qa-sentinel/ff2");
    sh(repo, "branch", "-q", "-D", "qa-sentinel/ff2");

    // A later human MR, branched after MR 2 was merged, touching MR 2's spec: not the agent MR's review.
    sh(repo, "checkout", "-q", "-b", "human", "main");
    write(repo, "tests/ff2.spec.ts", "// later work by someone else\n");
    sh(repo, "commit", "-qam", "later change");
    sh(repo, "push", "-q", "origin", "human:refs/merge-requests/10/head");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--ff-only", "human");
    sh(repo, "branch", "-q", "-D", "human");

    // MR 3: squash, reviewer edit, source branch deleted (only the MR ref keeps the commits).
    agent(repo, "qa-sentinel/sq", "tests/sq.spec.ts", "run-sq");
    const msg = sh(repo, "log", "-1", "--format=%B");
    write(repo, "tests/sq.spec.ts", "// reviewer\n");
    sh(repo, "commit", "-qam", "review");
    sh(repo, "push", "-q", "origin", "qa-sentinel/sq:refs/merge-requests/3/head");
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--squash", "qa-sentinel/sq");
    sh(repo, "commit", "-q", "-m", `Squashed\n\n${msg}`);
    sh(repo, "branch", "-q", "-D", "qa-sentinel/sq");
    sh(repo, "reflog", "expire", "--expire=now", "--all");
    sh(repo, "gc", "-q", "--prune=now");

    const before = Object.fromEntries(agentCommits(repo, "main").map((x) => [x.runId, x.state]));
    expect(before).toMatchObject({ "run-ff": "merged-unedited", "run-ff2": "merged-unedited", "run-sq": "merged-unknown" });

    expect(fetchReviewRefs(repo)).toBe(true);
    const after = Object.fromEntries(agentCommits(repo, "main").map((x) => [x.runId, x.state]));
    expect(after).toEqual({ "run-ff": "merged-edited", "run-ff2": "merged-unedited", "run-sq": "merged-edited" });
  });
});

describe("cost by change size (B6)", () => {
  it("groups cost by diff size and suggests budgets from p90 once there are enough runs", async () => {
    const { computeMetrics, metricsMarkdown } = await import("../src/commands/metrics.js");
    const run = (kind: string, diffLines: number, costUsd: number, status = "ok") => ({ kind, runId: "r", startedAt: "2026-10-01T00:00:00Z", finishedAt: "x", outcome: "reported", agent: { status, costUsd }, size: { changedFiles: 1, diffLines } }) as never;
    const runs = [...Array.from({ length: 9 }, (_, i) => run("gap-report", 20, 0.2 + i * 0.01)), run("gap-report", 2000, 1.9, "max-budget")];
    const m = computeMetrics(runs, []);
    expect(m.bySize.map((x) => [x.bucket, x.runs, x.hitBudget])).toEqual([
      ["< 50 lines", 9, 0],
      ["> 1000", 1, 1],
    ]);
    expect(m.suggestedBudgets).toEqual([{ kind: "gap-report", runs: 10, p90CostUsd: 0.28, suggestedUsd: 0.5 }]);
    expect(metricsMarkdown(m)).toContain("Budgets these runs suggest");
  });
});

describe("budget suggestions from story records", () => {
  const rec = async (key: string, cost: number, o: { generate?: boolean; days?: string[] } = {}) => {
    const { emptyRecord } = await import("../src/stories/record.js");
    const r = emptyRecord(key);
    r.totalCostUsd = cost;
    if (o.generate !== false) r.jobs.g = { key: "g", kind: "generate", state: "done", startedAt: "2026-10-01T00:00:00Z", attempts: 1, costUsd: cost };
    r.ledger = (o.days ?? []).map((d, i) => ({ at: `${d}T0${i % 9}:00:00Z`, job: "g", kind: "generate" as const, costUsd: cost / Math.max(1, (o.days ?? []).length) }));
    r.updatedAt = "2026-10-20T00:00:00Z";
    return r;
  };
  it("perStory = p90 of story totals (stories with a generate job) x 1.5; perDay = p90 of daily sums x 1.5; perMonth = perDay x 22 to the next $5", async () => {
    const { suggestAutomationBudgets } = await import("../src/commands/metrics.js");
    // 12 stories with totals 1..12 dollars, each spent on its own day; one more story with no generate job is not counted.
    const records = [
      ...(await Promise.all(Array.from({ length: 12 }, (_, i) => rec(`SHOP-${100 + i}`, i + 1, { days: [`2026-10-${String(i + 1).padStart(2, "0")}`] })))),
      await rec("SHOP-999", 500, { generate: false }),
    ];
    const s = suggestAutomationBudgets(records);
    expect(s.stories).toBe(12);
    expect(s.days).toBe(12);
    // p90 of 1..12 is the 11th value (11) -> 16.5; the daily sums are the same numbers.
    expect(s.perStoryUsd).toBe(16.5);
    expect(s.perDayUsd).toBe(16.5);
    expect(s.perMonthUsd).toBe(365); // 16.5 x 22 = 363 -> next $5
    expect(s.notes).toEqual([]);
  });
  it("says how many are still needed below 10, and counts the same story once across folders", async () => {
    const { suggestAutomationBudgets } = await import("../src/commands/metrics.js");
    const few = await Promise.all(Array.from({ length: 9 }, (_, i) => rec(`SHOP-${i}`, 2, { days: [`2026-10-0${i + 1}`] })));
    const s = suggestAutomationBudgets([...few, ...few]); // a downloaded cache holding the same records
    expect(s).toMatchObject({ stories: 9, days: 9 });
    expect(s.perStoryUsd).toBeUndefined();
    expect(s.perDayUsd).toBeUndefined();
    expect(s.perMonthUsd).toBeUndefined();
    expect(s.notes.join(" ")).toMatch(/needs 10 stories with a generate job \(found 9\)/);
    expect(s.notes.join(" ")).toMatch(/need 10 days with AI spend \(found 9\)/);
  });
  it("a story seen in two folders with different jobs is summed (a job in both counts once); $0 dry-run stories are not samples", async () => {
    const { suggestAutomationBudgets } = await import("../src/commands/metrics.js");
    const a = await rec("SHOP-1", 3);
    const b = await rec("SHOP-1", 4);
    a.jobs = { g1: { key: "g1", kind: "generate", state: "done", startedAt: "2026-10-01T00:00:00Z", attempts: 1, costUsd: 3 }, shared: { key: "shared", kind: "generate", state: "done", startedAt: "2026-10-02T00:00:00Z", attempts: 1, costUsd: 1 } };
    b.jobs = { g2: { key: "g2", kind: "generate", state: "done", startedAt: "2026-10-03T00:00:00Z", attempts: 1, costUsd: 4 }, shared: { key: "shared", kind: "generate", state: "done", startedAt: "2026-10-02T00:00:00Z", attempts: 1, costUsd: 1 } };
    a.totalCostUsd = 4;
    b.totalCostUsd = 5;
    const others = await Promise.all(Array.from({ length: 9 }, (_, i) => rec(`SHOP-${10 + i}`, 1, { days: [`2026-10-${String(i + 1).padStart(2, "0")}`] })));
    const dry = await Promise.all(Array.from({ length: 5 }, (_, i) => rec(`SHOP-${50 + i}`, 0)));
    const eight = await rec("SHOP-2", 8);
    const s = suggestAutomationBudgets([a, b, eight, ...others, ...dry]);
    expect(s.stories).toBe(11); // SHOP-1 once (3 + 1 + 4 = 8), SHOP-2, nine others; the five $0 stories are left out
    expect(s.perStoryUsd).toBe(12); // p90 of [1 x 9, 8, 8] is 8 (SHOP-1 summed, not dropped) -> x 1.5
  });
  it("is part of the report and the JSON, and --records reads a folder of downloaded records read only", async () => {
    const { computeMetrics, metricsMarkdown } = await import("../src/commands/metrics.js");
    const { readRecordsFrom } = await import("../src/stories/record.js");
    const dir = tmp();
    for (let i = 0; i < 10; i++) write(dir, `cache/.qa-sentinel/stories/SHOP-${i}.json`, JSON.stringify(await rec(`SHOP-${i}`, 3, { days: [`2026-10-${String(i + 1).padStart(2, "0")}`] })));
    write(dir, "cache/.qa-sentinel/stories/_sweep.json", "{}");
    write(dir, "cache/.qa-sentinel/stories/SHOP-bad.json", "{not json");
    const records = readRecordsFrom(dir);
    expect(records).toHaveLength(10);
    expect(fs.existsSync(path.join(dir, "cache/.qa-sentinel/stories/SHOP-bad.json"))).toBe(true); // not moved aside
    const m = computeMetrics([], [], undefined, records);
    expect(m.suggestedAutomationBudgets).toMatchObject({ stories: 10, days: 10, perStoryUsd: 4.5, perDayUsd: 4.5, perMonthUsd: 100 });
    const md = metricsMarkdown(m);
    expect(md).toContain("automation.budgets.perStoryUsd | $4.50");
    expect(md).toContain("automation.budgets.perMonthUsd | $100.00");
    expect(metricsMarkdown(computeMetrics([], [], undefined, []))).toMatch(/perStoryUsd needs 10 stories/);
  });
});

describe("story-mode run size counts every part", () => {
  it("the manifest's size.diffLines is the sum of all parts' diff lines, and changedFiles all their files", async () => {
    const { ConfigSchema, writeConfig } = await import("../src/config.js");
    const { combinedChange } = await import("../src/story.js");
    const { startManifest, createRunDir } = await import("../src/run.js");
    const dir = tmp();
    const c = ConfigSchema.parse({ version: 1, mode: "existing", project: { name: "t" }, tests: { api: { framework: "playwright", runCommand: "x" } }, ci: { platform: "gitlab" } });
    writeConfig(dir, c);
    const diff = (n: number, file: string) => [`diff --git a/${file} b/${file}`, `--- a/${file}`, `+++ b/${file}`, "@@ -1 +1 @@", ...Array.from({ length: n }, (_, i) => `+line ${i}`), "-old"].join("\n");
    const part = (name: string, n: number) => ({ service: { name, path: `../${name}`, kind: "api" as const, routes: [], dependsOn: [] }, repo: `/x/${name}`, cs: { base: "a".repeat(40), head: "b".repeat(40), files: [`src/${name}.ts`], diff: diff(n, `src/${name}.ts`) }, heads: ["b".repeat(40)], relevant: [`src/${name}.ts`], merged: true, label: `${name} merged` });
    const { cs, relevant, service } = combinedChange("SHOP-1", [part("orders", 7), part("storefront", 5)] as never);
    const run = createRunDir(dir, "gen-story");
    const m = startManifest(dir, c, run, "generate", { service, base: cs.base, head: cs.head, changedFiles: relevant, diff: cs.diff }, { source: "none", acceptanceCriteria: [] } as never);
    // (7 + 1) + (5 + 1) lines starting with + or -, not the file headers (--- / +++) and not the "# =====" part headers.
    expect(m.size).toMatchObject({ changedFiles: 2, diffLines: 14 });
  });
});
