import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { describe, expect, it } from "vitest";
import { initCommand } from "../src/commands/init.js";
import { lessonsCommand } from "../src/commands/lessons.js";
import { agentCommits } from "../src/commands/metrics.js";
import { applyLessons, processedCommits, reviewerEdits, validateLessons } from "../src/review/lessons.js";
import type { AgentEngine, AgentTask } from "../src/engines/AgentEngine.js";

const sh = (cwd: string, ...args: string[]) =>
  execFileSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" } }).trim();
const write = (repo: string, f: string, body: string) => {
  fs.mkdirSync(path.dirname(path.join(repo, f)), { recursive: true });
  fs.writeFileSync(path.join(repo, f), body);
};

async function repoWithReviewedMrs() {
  const repo = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "qas-lessons-")), "qa-tests");
  fs.mkdirSync(repo);
  sh(repo, "init", "-q", "-b", "main");
  await initCommand({ cwd: repo, yes: true, mode: "scratch", ci: "gitlab", level: "maintenance", name: "l" });
  sh(repo, "add", "-A");
  sh(repo, "commit", "-q", "-m", "init");
  const agent = (branch: string, file: string, body: string, runId: string) => {
    sh(repo, "checkout", "-q", "-b", branch, "main");
    write(repo, file, body);
    sh(repo, "add", "-A");
    sh(repo, "commit", "-q", "-m", `test(orders): QA agent updates for abc\n\nGenerated by qa-sentinel 0.7.0 from orders@abc.\nRisk: low. Verification: VERIFIED. Run: ${runId}`);
    return sh(repo, "rev-parse", "HEAD");
  };
  // 1. Merge commit; the reviewer strengthened an assertion first.
  const a = agent("qa-sentinel/a", "tests/api/a.spec.ts", "expect(res.status()).toBe(400);\n", "run-a");
  write(repo, "tests/api/a.spec.ts", "expect(res.status()).toBe(400);\nexpect((await res.json()).error).toBe('qty must be a positive integer');\n");
  sh(repo, "commit", "-qam", "review: assert the error message");
  sh(repo, "checkout", "-q", "main");
  sh(repo, "merge", "-q", "--no-ff", "-m", "Merge a", "qa-sentinel/a");
  // 2. Squash; the reviewer changed only a test email.
  const b = agent("qa-sentinel/b", "tests/api/b.spec.ts", "const email = 'x@example.test';\n", "run-b");
  const msg = sh(repo, "log", "-1", "--format=%B");
  write(repo, "tests/api/b.spec.ts", "const email = 'qa@example.test';\n");
  sh(repo, "commit", "-qam", "review: email");
  sh(repo, "checkout", "-q", "main");
  sh(repo, "merge", "-q", "--squash", "qa-sentinel/b");
  sh(repo, "commit", "-q", "-m", `Squashed\n\n${msg}`);
  // 3. Merged as is: nothing to learn.
  agent("qa-sentinel/c", "tests/api/c.spec.ts", "ok\n", "run-c");
  sh(repo, "checkout", "-q", "main");
  sh(repo, "merge", "-q", "--no-ff", "-m", "Merge c", "qa-sentinel/c");
  return { repo, a, b };
}

/** Stands in for the agent: writes the lessons JSON it is asked for and records the prompt. */
function fakeEngine(result: (prompt: string) => unknown): AgentEngine & { tasks: AgentTask[] } {
  const tasks: AgentTask[] = [];
  return {
    tasks,
    async run(t: AgentTask) {
      tasks.push(t);
      const out = t.prompt.match(/as JSON to (\S+)\. That/)![1];
      fs.writeFileSync(path.join(t.cwd, out), JSON.stringify(result(t.prompt)));
      return { ok: true, status: "ok", result: "done", costUsd: 0.05 };
    },
  } as AgentEngine & { tasks: AgentTask[] };
}

describe("learning from review", () => {
  it("finds the reviewer's edits on agent MRs (merge and squash), skipping MRs merged as is", async () => {
    const { repo, a, b } = await repoWithReviewedMrs();
    const edits = reviewerEdits(repo, agentCommits(repo, "main"));
    expect(edits.map((e) => [e.sha, e.how])).toEqual(expect.arrayContaining([[a, "merge"], [b, "squash"]]));
    expect(edits).toHaveLength(2);
    expect(edits.find((e) => e.sha === a)!.diff).toContain("+expect((await res.json()).error)");
    expect(edits.find((e) => e.sha === b)!.diff).toContain("+const email = 'qa@example.test';");
  });

  it("proposes lessons in kb/review-lessons.md on a branch, records what it reviewed, and learns nothing twice", async () => {
    const { repo, a, b } = await repoWithReviewedMrs();
    const engine = fakeEngine(() => ({
      schemaVersion: 1,
      lessons: [{ lesson: "Assert the error message the acceptance criterion names, not only the status code.", why: "The reviewer added the message check.", example: "toBe(400) → also .error", appliesTo: "api", sources: [a.slice(0, 8)] }],
      skipped: [{ commit: b.slice(0, 8), reason: "test email only" }],
    }));
    expect(await lessonsCommand({ cwd: repo, engine })).toBe(0);
    expect(engine.tasks[0].write).toEqual({ allowed: [expect.stringMatching(/lessons\.json$/)], blocked: [] });
    expect(sh(repo, "branch", "--show-current")).toBe("qa-sentinel/review-lessons");
    expect(sh(repo, "diff", "--name-only", "main", "HEAD")).toBe("kb/review-lessons.md");
    const md = fs.readFileSync(path.join(repo, "kb/review-lessons.md"), "utf8");
    expect(md).toContain("## Assert the error message the acceptance criterion names, not only the status code.");
    expect(md).toContain(`- From review of: ${a.slice(0, 8)}`);
    expect([...processedCommits(md)].sort()).toEqual([a.slice(0, 8), b.slice(0, 8)].sort());
    // Merged: the next run has nothing new and doesn't call the agent.
    sh(repo, "checkout", "-q", "main");
    sh(repo, "merge", "-q", "--no-ff", "-m", "Merge lessons", "qa-sentinel/review-lessons");
    const again = fakeEngine(() => ({}));
    expect(await lessonsCommand({ cwd: repo, engine: again })).toBe(0);
    expect(again.tasks).toHaveLength(0);
  });

  it("checks the agent's answer: known commits only, real headings for updates; strengthens instead of repeating", () => {
    const md = applyLessons(undefined, { schemaVersion: 1, lessons: [{ lesson: "Prefer roles over CSS selectors in page objects.", why: "w", appliesTo: "web", sources: ["aaaaaaaa"] }], skipped: [] }, ["aaaaaaaa11"]);
    expect(validateLessons({ schemaVersion: 1, lessons: [{ lesson: "Something general enough here.", why: "w", appliesTo: "all", sources: ["bbbbbbbb"] }] }, ["aaaaaaaa11"], []).errors[0]).toMatch(/not one of the reviewed commits/);
    expect(validateLessons({ schemaVersion: 1, lessons: [{ lesson: "Something general enough here.", why: "w", appliesTo: "all", sources: ["aaaaaaaa"], updates: "No such lesson" }] }, ["aaaaaaaa11"], ["Prefer roles over CSS selectors in page objects."]).errors[0]).toMatch(/not an existing lesson heading/);
    const more = applyLessons(md, { schemaVersion: 1, lessons: [{ lesson: "x".repeat(20), why: "w", appliesTo: "web", sources: ["cccccccc"], updates: "Prefer roles over CSS selectors in page objects.", example: "#buy → getByRole('button')" }], skipped: [] }, ["cccccccc22"]);
    expect(more.match(/^## /gm)).toHaveLength(1);
    expect(more).toContain("- Seen again: cccccccc (#buy → getByRole('button'))");
    expect([...processedCommits(more)].sort()).toEqual(["aaaaaaaa", "cccccccc"]);
  });
});
