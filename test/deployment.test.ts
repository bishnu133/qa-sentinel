import fs from "node:fs";
import http from "node:http";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import YAML from "yaml";
import { applyDeploymentGate, needsFromCommits } from "../src/deployment.js";
import { ConfigSchema } from "../src/config.js";
import { EXIT_STILL_WAITING, postDeployCommand } from "../src/commands/postDeploy.js";

const sh = (cwd: string, ...args: string[]) =>
  execFileSync("git", args, { cwd, encoding: "utf8", env: { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" } }).trim();

let deployed = "";
let server: http.Server;
let base = "";
beforeAll(async () => {
  server = http.createServer((req, res) => {
    res.setHeader("content-type", "application/json");
    if (req.url === "/orders/version") return void res.end(JSON.stringify({ commit: deployed }));
    res.end("{}");
  });
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", () => r()));
  base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
});
afterAll(() => server.close());

const report = (status: "FAILED" | "VERIFIED", extra: { name: string; status: string }[] = []) =>
  ({ status, checks: [{ name: "tests", status: status === "FAILED" ? "failed" : "passed", detail: "" }, ...extra], specs: [], cases: [], counts: { total: 1, passed: 0, failed: 1, skipped: 0 } }) as never;

describe("waiting for deployment (C1)", () => {
  it("failed only because the change isn't deployed: WAITING_FOR_DEPLOYMENT, not FAILED", () => {
    const waiting = [{ service: "orders", sha: "abc12345", deployed: "def67890", includesChange: false }];
    expect(applyDeploymentGate(report("FAILED"), waiting).status).toBe("WAITING_FOR_DEPLOYMENT");
    // A type error is a real failure, deployed or not.
    expect(applyDeploymentGate(report("FAILED", [{ name: "typecheck", status: "failed" }]), waiting).status).toBe("FAILED");
    expect(applyDeploymentGate(report("FAILED"), [{ ...waiting[0], includesChange: true }]).status).toBe("FAILED");
    const v = applyDeploymentGate(report("VERIFIED"), [{ ...waiting[0], includesChange: true, deployed: "abc12345" }]);
    expect(v.status).toBe("VERIFIED");
    expect(v.checks.at(-1)).toMatchObject({ name: "deployment", status: "passed" });
  });

  it("reads the service commits an agent branch was written for", () => {
    const repo = fs.mkdtempSync(path.join(os.tmpdir(), "qas-needs-"));
    sh(repo, "init", "-q", "-b", "main");
    sh(repo, "commit", "-q", "--allow-empty", "-m", "base");
    const b = sh(repo, "rev-parse", "HEAD");
    sh(repo, "commit", "-q", "--allow-empty", "-m", "test(story SHOP-1): QA agent updates\n\nGenerated by qa-sentinel 0.8.0 from orders@abcdef1234, web@1234567abc.\nRisk: low.");
    const c = ConfigSchema.parse({ version: 1, mode: "scratch", project: { name: "p" }, tests: { api: { framework: "playwright", runCommand: "x" } }, ci: { platform: "gitlab" }, workspace: { services: [{ name: "orders", path: "../o", version: { path: "/v" } }, { name: "web", path: "../w", kind: "web" }] } });
    expect(needsFromCommits(c, repo, b).map((n) => [n.service.name, n.sha])).toEqual([
      ["orders", "abcdef1234"],
      ["web", "1234567abc"],
    ]);
  });
});

describe("post-deploy (C2)", () => {
  it("checks the story's services are deployed, then runs its tests there; still waiting = exit 75", async () => {
    const work = fs.mkdtempSync(path.join(os.tmpdir(), "qas-postdeploy-"));
    const svc = path.join(work, "orders");
    fs.mkdirSync(svc);
    sh(svc, "init", "-q", "-b", "main");
    sh(svc, "commit", "-q", "--allow-empty", "-m", "start");
    const old = sh(svc, "rev-parse", "HEAD");
    sh(svc, "commit", "-q", "--allow-empty", "-m", "SHOP-7: delivery slots");
    const change = sh(svc, "rev-parse", "HEAD");

    const qa = path.join(work, "qa-tests");
    fs.mkdirSync(path.join(qa, "tests/api"), { recursive: true });
    fs.writeFileSync(path.join(qa, "tests/api/slots.spec.ts"), 'test("books a slot @service:orders @story:SHOP-7 @ac:AC-1", async () => { expect(1).toBe(1); });\n');
    // A runner that writes JUnit where verification.junitPath says.
    fs.writeFileSync(path.join(qa, "run.mjs"), `import fs from "node:fs"; fs.mkdirSync("out", { recursive: true }); fs.writeFileSync("out/junit.xml", '<testsuite><testcase name="books a slot" classname="tests/api/slots.spec.ts"/></testsuite>');`);
    fs.writeFileSync(
      path.join(qa, "qa-sentinel.config.yaml"),
      YAML.stringify({
        version: 1,
        mode: "existing",
        project: { name: "p" },
        tests: { api: { framework: "other", runCommand: "node run.mjs" } },
        ci: { platform: "gitlab" },
        verification: { junitPath: "out/junit.xml", typecheck: "never" },
        environments: { sit: { baseUrl: base } },
        workspace: { services: [{ name: "orders", path: "../orders", version: { path: "/orders/version", field: "commit" } }] },
      }),
    );
    sh(qa, "init", "-q", "-b", "main");

    deployed = old; // SIT still runs the old commit
    const t0 = Date.now();
    expect(await postDeployCommand({ cwd: qa, env: "sit", stories: ["SHOP-7"], waitMinutes: 0 })).toBe(EXIT_STILL_WAITING);
    expect(fs.readFileSync(path.join(qa, "qa-post-deploy.md"), "utf8")).toContain("## SHOP-7: ⏳ waiting for deployment");

    // Deployed while we wait: found on the next check, then the tests run.
    setTimeout(() => (deployed = change), 150);
    expect(await postDeployCommand({ cwd: qa, env: "sit", service: "orders", sha: change, waitMinutes: 0.05, pollMs: 100 })).toBe(0);
    const md = fs.readFileSync(path.join(qa, "qa-post-deploy.md"), "utf8");
    expect(md).toContain("## SHOP-7: ✅ tests passed");
    expect(md).toContain("✅ VERIFIED");
    expect(Date.now() - t0).toBeLessThan(20_000);
  });
});

describe("deployment ancestry that can't be decided", () => {
  it("is unknown, not 'not deployed', so real failures stay FAILED", async () => {
    const { checkDeployment } = await import("../src/feature/manifest.js");
    const repo = fs.mkdtempSync(path.join(os.tmpdir(), "qas-anc-"));
    sh(repo, "init", "-q", "-b", "main");
    sh(repo, "commit", "-q", "--allow-empty", "-m", "change");
    const change = sh(repo, "rev-parse", "HEAD");
    deployed = "0123456789abcdef0123456789abcdef01234567"; // a later commit this clone doesn't have
    const svc = { name: "orders", path: ".", dependsOn: [], kind: "api", routes: [], version: { path: "/orders/version", field: "commit" } } as never;
    const d = await checkDeployment({ service: "orders", source: "git", sha: change, merged: true }, svc, "sit", base, repo);
    expect(d?.includesChange).toBeUndefined();
    const noClone = await checkDeployment({ service: "orders", source: "git", sha: change, merged: true }, svc, "sit", base);
    expect(noClone?.includesChange).toBeUndefined();
    expect(applyDeploymentGate(report("FAILED"), [{ service: "orders", sha: change, deployed, includesChange: undefined }]).status).toBe("FAILED");
  });
});
